#!/usr/bin/env python3
"""Make /etc/udev/rules.d/90-xpisode-can.rules from a station's CAN adapter serials.

    sudo host/can_rules.py [STATION]          write it if it changed, reload and trigger udev
    host/can_rules.py [STATION] --check       print what would change; write nothing

STATION is robots/<STATION>/ (default: the one whose machine.env has this machine's hostname).
Its can.toml (``<role> = "<serial>"``) is the only source: the adapter with that serial is named
``can_<role>`` (the same names on every YAM machine) and brought up at 1 Mbit/s, and
ModemManager leaves it alone. It refuses while a serial is FILL (or empty) or two roles share one.
It never sends anything on a bus. Exit status: 0 done, 1 refused, 2 usage.
"""

from __future__ import annotations

import argparse
import difflib
import os
import re
import socket
import tomllib
import subprocess
import sys
from pathlib import Path

SITE = Path(__file__).resolve().parents[1]
TARGET = Path("/etc/udev/rules.d/90-xpisode-can.rules")
SERIAL = re.compile(r"^[0-9A-Fa-f]{8,32}$")
RULE = (
    'SUBSYSTEM=="net", ACTION=="add", KERNEL=="can*", ATTRS{{serial}}=="{serial}", '
    'NAME="{name}", ENV{{ID_MM_DEVICE_IGNORE}}="1", '
    'RUN+="/usr/sbin/ip link set {name} up type can bitrate 1000000"'
)


def host_of(env: Path) -> str | None:
    """``XPISODE_HOST`` of a machine.env."""
    for line in env.read_text().splitlines():
        match = re.match(r"^XPISODE_HOST=(\S+)", line.strip())
        if match:
            return match[1].strip("\"'")
    return None


def station_dir(name: str | None) -> Path:
    robots = SITE / "robots"
    if name:
        folder = robots / name
        if not (folder / "can.toml").is_file():
            raise SystemExit(f"no robots/{name}/can.toml")
        return folder
    marker = SITE / ".station"
    if marker.is_file() and marker.read_text().strip():
        return station_dir(marker.read_text().strip())
    host = socket.gethostname().split(".")[0]
    for env in sorted(robots.glob("*/machine.env")):
        if host_of(env) == host:
            return env.parent
    raise SystemExit("no station: write its name into .station (echo <station> > .station), or give it")


def rules(folder: Path) -> tuple[str, list[str]]:
    """The rule file's text, and what is wrong with the mapping (empty: nothing)."""
    with (folder / "can.toml").open("rb") as file:
        roles = {str(k): str(v).strip() for k, v in tomllib.load(file).items()}
    problems: list[str] = []
    if not roles:
        problems.append("can.toml maps no role")
    owners: dict[str, list[str]] = {}
    for role, serial in roles.items():
        if not re.fullmatch(r"[a-z][a-z0-9_]*", role):
            problems.append(f"{role!r} is not a role name (can_<role> must be an interface name)")
        if not serial or serial.upper().startswith("FILL"):
            problems.append(f"{role}: serial not filled in")
        elif not SERIAL.match(serial):
            problems.append(f"{role}: {serial!r} does not look like an adapter serial")
        else:
            owners.setdefault(serial.upper(), []).append(role)
    for serial, shared in owners.items():
        if len(shared) > 1:
            problems.append(f"{serial} is given to {', '.join(shared)}")
    lines = [
        f"# Generated by host/can_rules.py from robots/{folder.name}/can.toml; edit that, not this.",
        "# Each CAN adapter, by serial, named after its arm role and brought up at 1 Mbit/s.",
        *(RULE.format(serial=serial, name=f"can_{role}") for role, serial in sorted(roles.items())),
    ]
    return "\n".join(lines) + "\n", problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("station", nargs="?")
    parser.add_argument("--check", action="store_true", help="print the diff; write nothing")
    args = parser.parse_args()
    folder = station_dir(args.station)
    text, problems = rules(folder)
    if problems:
        print(f"can_rules: not generated from robots/{folder.name}/can.toml:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    old = TARGET.read_text() if TARGET.is_file() else ""
    diff = list(difflib.unified_diff(old.splitlines(keepends=True), text.splitlines(keepends=True),
                                     str(TARGET), f"{TARGET} (new)"))
    if not diff:
        print(f"  unchanged  {TARGET}")
        return 0
    sys.stdout.writelines(diff)
    if args.check:
        return 0
    if os.geteuid() != 0:
        print("can_rules: run with sudo to write it", file=sys.stderr)
        return 2
    TARGET.write_text(text)
    print(f"  changed    {TARGET}")
    subprocess.run(["udevadm", "control", "--reload"], check=True)
    subprocess.run(["udevadm", "trigger", "--subsystem-match=net", "--action=add"], check=True)
    print("  udev reloaded and triggered; check with host/can_list.sh")
    return 0


if __name__ == "__main__":
    sys.exit(main())
